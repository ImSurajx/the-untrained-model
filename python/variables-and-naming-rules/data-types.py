# data types in python
# every value in python has a type, python decides the type automatically you just assign the value

# integer -> int -> ex: 42 -> whole numbers
# float -> float -> ex: 3.14 -> decimal numbers
# string -> str -> ex: "Hello" -> text
# boolean -> bool -> ex: true/false -> yes or no values

# python aslo has complex (complex numbers) and None (NoneType)

name = "Suraj Kumar"
age = 25
gender = "Male"
is_student = True
float_num = 12.4
print(type(name))
print(type(age))
print(type(gender))
print(type(is_student))
print(type(float_num))
