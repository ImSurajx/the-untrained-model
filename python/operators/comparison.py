# comparision operators: compare two values and always return a boolean - either True or False
# = -> equal to -> 5 == 5 -> True
# != -> not equal to -> 5 != 3 -> True
# > greather than -> 7 > 3 -> True
# < less than -> 2 < 1 -> False
# >= greater than or equal -> 5 >= 5 -> Ture
# <= less than or equal -> 4 <= 3 False
print(5 == 5)
print(5 != 3)
print(7 > 3)
print(2 < 1)
print(5 >= 5)
print(4 <= 3)
