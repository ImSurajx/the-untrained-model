# take two numbers as input from the user. print sum, difference, product and remainder.

num_one = int(input("enter first number: "))
num_two = int(input("enter second number: "))

print(f"sum is: {num_one + num_two}")
print(f"difference is: {num_one - num_two}")
print(f"product is: {num_one * num_two}")
print(f"remainder is: {num_one / num_two}")
