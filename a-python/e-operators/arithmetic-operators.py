# arithmetic operators are used to perform basic mathematical operations.
a = 59
b = 10
print(f"addition: {a+b}")
print(f"subtraction: {a-b}")
print(f"multiplication: {a*b}")
print(f"division: {a/b}") # 5.9 -> float
print(f"floor division: {a//b}") # 5 -> lower integer
print(f"modulus: {a%b}") # remainder = 9
print(f"exponentiations: {a**2}") # 2^5 = 32
